"""Build deterministic, secret-free effective configuration observations."""

from hashlib import sha256
from typing import Any

from llm_grounding.infrastructure.config.models import ArchitectureConfig
from llm_grounding.ingestion.models import IngestionConfig
from llm_grounding.observability.models import (
    ArchitectureConfiguration,
    CorpusConfiguration,
    EffectiveConfiguration,
    EmbeddingConfiguration,
    GenerationConfiguration,
    IngestionConfiguration,
    PromptConfiguration,
    RetrievalConfiguration,
)


def _hash(value: Any) -> str:
    """Hash canonical JSON generated by Pydantic's sorted model representation."""
    import json

    encoded = json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    return sha256(encoded).hexdigest()


def build_effective_configuration(
    architecture: ArchitectureConfig,
    ingestion: IngestionConfig,
    *,
    corpus_id: str | None = None,
    prompt_id: str | None = None,
    prompt_version: str | None = None,
    prompt_hash: str | None = None,
) -> EffectiveConfiguration:
    """Build an observation from actual typed runtime configuration.

    Endpoint credentials, URLs, and other provider secrets are deliberately not
    copied into the resulting schema.
    """
    architecture_data = architecture.model_dump(
        mode="json", exclude={"reasoner": {"model": {"base_url"}}}
    )
    return EffectiveConfiguration(
        architecture=ArchitectureConfiguration(
            name=architecture.name,
            version=architecture.version,
            config_hash=_hash(architecture_data),
        ),
        ingestion=IngestionConfiguration(
            parser=ingestion.parser,
            chunker=ingestion.chunker.type,
            target_chunk_size=ingestion.chunker.target_chars,
            overlap=ingestion.chunker.overlap_chars,
            config_hash=ingestion.identity(),
        ),
        embedding=EmbeddingConfiguration(
            model_id=ingestion.embedding.model,
            version=ingestion.embedding.revision,
            dimension=ingestion.embedding.dimension,
            normalization=ingestion.embedding.normalize,
            embedding_hash=ingestion.embedding.identity(),
        ),
        retrieval=RetrievalConfiguration(
            type=architecture.retriever.type,
            top_k=architecture.retriever.top_k,
            similarity_metric="cosine_similarity",
            context_limit=architecture.retriever.context_chars,
        ),
        generation=GenerationConfiguration(model_id=architecture.reasoner.model.name),
        prompt=PromptConfiguration(
            prompt_id=prompt_id or architecture.reasoner.prompt_id,
            prompt_version=prompt_version,
            prompt_hash=prompt_hash,
        ),
        corpus=CorpusConfiguration(corpus_id=corpus_id),
    )
